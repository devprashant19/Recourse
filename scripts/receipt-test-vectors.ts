/**
 * Generates the EIP-191 receipt test vectors used by the contract's unit tests
 * (contracts/recourse/src/tests/fixtures/receipt_vectors.json).
 *
 *   pnpm tsx scripts/receipt-test-vectors.ts
 *
 * Signatures come from ethers (RFC 6979, so deterministic) over the exact text
 * forms NEAR AI Cloud signs, and each is re-verified with ethers before being
 * written. The signing keys are derived from fixed public labels
 * (keccak256("recourse/test-vector/...")), so they are reproducible, hold
 * nothing, and no key material is committed to the repository.
 *
 * These vectors prove the contract's EIP-191 + ecrecover path agrees with a
 * standard Ethereum implementation. They do NOT replace Spike A: a real NEAR
 * AI Cloud signature must still be recorded and added as a vector.
 */

import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { Signature, Wallet, keccak256, toUtf8Bytes, verifyMessage } from "ethers";

/** A throwaway key derived from a public label: deterministic, worthless. */
const testKey = (label: string) => keccak256(toUtf8Bytes(`recourse/test-vector/${label}`));

const sha256 = (s: string) => createHash("sha256").update(s).digest("hex");
const SECP256K1_N = BigInt("0xfffffffffffffffffffffffffffffffebaaedce6af48a03bbfd25e8cd0364141");

async function main() {
  const tee = new Wallet(testKey("tee"));
  const other = new Wallet(testKey("other"));
  const model = "deepseek-ai/DeepSeek-V3.1";
  const requestHash = sha256('{"model":"m","messages":[{"role":"user","content":"extract"}]}');
  const responseHash = sha256('{"id":"chat-1","choices":[{"message":{"content":"{}"}}]}');

  const providerText = `${model}:${requestHash}:${responseHash}`;
  const gatewayText = `${requestHash}:${responseHash}`;

  const providerSig = await tee.signMessage(providerText);
  const gatewaySig = await tee.signMessage(gatewayText);
  const otherSig = await other.signMessage(providerText);

  // Same signature with the high-s twin: (r, n - s, flipped v). Valid in raw
  // ECDSA, but non-canonical; the contract must refuse it (malleability).
  const parsed = Signature.from(providerSig);
  const highS = (SECP256K1_N - BigInt(parsed.s)).toString(16).padStart(64, "0");
  const flippedV = parsed.v === 27 ? 28 : 27;
  const malleableSig = `0x${parsed.r.slice(2)}${highS}${flippedV.toString(16)}`;

  for (const [text, sig, who] of [
    [providerText, providerSig, tee.address],
    [gatewayText, gatewaySig, tee.address],
    [providerText, otherSig, other.address],
  ] as const) {
    if (verifyMessage(text, sig) !== who) throw new Error("ethers self-check failed");
  }

  const vectors = {
    note: "Generated by scripts/receipt-test-vectors.ts from label-derived throwaway keys. Not a NEAR AI Cloud signature.",
    model_id: model,
    request_hash: requestHash,
    response_hash: responseHash,
    tee_address: tee.address.toLowerCase(),
    other_address: other.address.toLowerCase(),
    provider_tee_text: providerText,
    provider_tee_signature: providerSig,
    gateway_text: gatewayText,
    gateway_signature: gatewaySig,
    other_signer_signature: otherSig,
    high_s_signature: malleableSig,
  };
  const out = fileURLToPath(
    new URL("../contracts/recourse/src/tests/fixtures/receipt_vectors.json", import.meta.url),
  );
  writeFileSync(out, JSON.stringify(vectors, null, 2) + "\n");
  console.log(`wrote ${out}`);
  console.log(`tee signer ${tee.address}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
